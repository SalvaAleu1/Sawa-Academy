"Personal Information and Privacy":`## Learning objectives
By the end of this lesson, you should be able to identify common types of personal data, explain why some information is more sensitive than other information, and make better decisions about what to share online.

## What counts as personal information?
Personal information is any information that can identify you directly or indirectly. Your full name, phone number, home address and identification number are obvious examples. Other information can become identifying when combined: your school, workplace, date of birth, usual travel route, photographs, device location, account usernames and family details.

Not all personal information carries the same level of risk. A public professional biography may be appropriate on a work profile, while a national identification number, password, one-time code, private health information or banking credential should never be posted publicly.

## Why privacy matters
Privacy is not about hiding everything. It is about controlling who can access information about you and for what purpose. Oversharing can make impersonation, scams, stalking, unwanted contact or account recovery attacks easier. A harmless-looking photo can reveal a location. A birthday post can reveal an answer used in security questions. A screenshot can accidentally expose a phone number or account balance.

## A practical sharing test
Before posting or sending information, ask four questions:
• Who will be able to see this?
• Do they need this information?
• Could this information be copied or forwarded?
• What could happen if the wrong person received it?

If the benefit of sharing is small but the possible harm is large, do not share it.

## Example
A student joins a public scholarship group and is asked to post a passport photo in the group chat for "verification." A safer response is to confirm whether the organization is genuine, use its official application channel, and only provide identity documents through a secure process when they are genuinely required.

## Check your understanding
Think of five pieces of information about yourself. Classify each as public, limited-share or highly sensitive. For each one, explain who genuinely needs access.

## Key takeaways
Privacy is a decision-making skill. Share the minimum information needed, understand the audience, and treat identity, financial, authentication and precise-location data as highly sensitive.`,

